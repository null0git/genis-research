"""Pull the handful of headline numbers the abstract needs, directly from
results/processed/*.json, so the abstract can never say something the
tables don't back up.

Reads: results/processed/e01..e04_metrics.json, plus any Wilcoxon-test
       output the analysis has produced (expected at
       results/processed/rq1_wilcoxon.json and rq2_wilcoxon.json -- these
       are produced by whatever script performs the Section 15
       (Generalization Analysis) statistical tests; not generated by this
       script itself).
Writes: results/processed/abstract_stats.json

Usage:
    python analysis/generate_abstract_stats.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.utils.config import get_repo_root  # noqa: E402
from src.utils.logging import get_logger  # noqa: E402

logger = get_logger(__name__)


def _load_optional(path: Path) -> Dict[str, Any] | None:
    if not path.exists():
        logger.warning("%s not found -- corresponding abstract stat(s) will be omitted.", path)
        return None
    with open(path) as f:
        return json.load(f)


def main() -> None:
    root = get_repo_root()
    e01 = _load_optional(root / "results/processed/e01_metrics.json")
    e02 = _load_optional(root / "results/processed/e02_metrics.json")
    e03 = _load_optional(root / "results/processed/e03_metrics.json")
    e04 = _load_optional(root / "results/processed/e04_metrics.json")
    rq1_test = _load_optional(root / "results/processed/rq1_wilcoxon.json")
    rq2_test = _load_optional(root / "results/processed/rq2_wilcoxon.json")

    stats: Dict[str, Any] = {}

    if e01 and e02:
        for model_name in e01["models"]:
            if model_name not in e02["models"]:
                continue
            random_f1 = e01["models"][model_name]["aggregate"]["macro_f1_mean"]
            loso_scores = [r["macro_f1"] for r in e02["models"][model_name]["per_run_metrics"]]
            loso_mean = sum(loso_scores) / len(loso_scores)
            stats[f"{model_name}_random_split_macro_f1"] = random_f1
            stats[f"{model_name}_loso_macro_f1"] = loso_mean
            stats[f"{model_name}_generalization_gap"] = random_f1 - loso_mean

    if e03 and e04:
        for model_name in e03["models"]:
            if model_name not in e04["models"]:
                continue
            random_f1 = e03["models"][model_name]["aggregate"]["macro_f1_mean"]
            loso_scores = [r["macro_f1"] for r in e04["models"][model_name]["per_run_metrics"]]
            loso_mean = sum(loso_scores) / len(loso_scores)
            stats[f"{model_name}_random_split_macro_f1"] = random_f1
            stats[f"{model_name}_loso_macro_f1"] = loso_mean
            stats[f"{model_name}_generalization_gap"] = random_f1 - loso_mean

    if rq1_test:
        stats["rq1_wilcoxon"] = rq1_test
    if rq2_test:
        stats["rq2_wilcoxon"] = rq2_test

    out_path = root / "results/processed/abstract_stats.json"
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(stats, fh, indent=2, default=str)
    logger.info("Wrote %s -- use these values, and only these, to fill the Abstract placeholders.", out_path)


if __name__ == "__main__":
    main()
